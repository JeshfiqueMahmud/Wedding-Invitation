-- ---------------------------------------------------------------------------
-- 1. RSVPs
-- ---------------------------------------------------------------------------
create table if not exists public.rsvps (
  id            bigint generated by default as identity primary key,
  name          text        not null,
  phone         text        default '',
  email         text        default '',
  attendance    text        not null check (attendance in ('both', 'holud', 'reception', 'unable')),
  guests_count  integer     not null default 1 check (guests_count between 1 and 50),
  dietary       text        default '',
  message       text        default '',
  created_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 2. Guestbook wishes
-- ---------------------------------------------------------------------------
create table if not exists public.guestbook_messages (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  message     text        not null,
  likes       integer     not null default 0,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 3. Website images — which photo goes where.
--    key      : a stable slot name, e.g. 'couple' or 'gallery-3'
--    section  : 'blessing' (the arch portrait) or 'gallery'
--    url      : public Supabase Storage URL
--    path     : file path inside the "images" bucket (used to delete old files)
-- ---------------------------------------------------------------------------
create table if not exists public.images (
  id          bigint generated by default as identity primary key,
  key         text        not null unique,
  section     text        not null,
  title       text        default '',
  subtitle    text        default '',
  url         text        not null,
  path        text,
  sort_order  integer     not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists images_section_order_idx on public.images (section, sort_order);

-- ---------------------------------------------------------------------------
-- 4. Row Level Security
--    The Express backend connects as the database owner and is not affected.
--    The browser only ever holds the public "anon" key, which may:
--      * read the images table (so photos load even while the backend sleeps)
--      * nothing else — RSVPs and wishes are only reachable through the backend.
-- ---------------------------------------------------------------------------
alter table public.rsvps              enable row level security;
alter table public.guestbook_messages enable row level security;
alter table public.images             enable row level security;

-- Newer Supabase projects don't grant table access to the anon role by default.
-- Give it read access to images only (RLS above still applies on top of this).
grant select on public.images to anon, authenticated;

drop policy if exists "Anyone can read site images" on public.images;
create policy "Anyone can read site images"
  on public.images for select
  to anon, authenticated
  using (true);

-- ---------------------------------------------------------------------------
-- 5. Storage bucket "images" (public = anyone can VIEW files by URL).
--    No insert/update/delete policies are created on purpose: only the backend,
--    using the secret service key, can upload, replace or delete files.
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('images', 'images', true, 8388608, array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'image/avif'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;
